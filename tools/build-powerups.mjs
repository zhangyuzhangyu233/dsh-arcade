// Bake the power-up SVGs into `src/generated/powerups.js` as themed data URIs.
//
// The source logos use `fill="currentColor"`, which is meaningless inside an
// <img> (it resolves to black), so this bakes the line color of each UI theme
// into a separate copy: black for the light theme, white for dark — exactly
// what `currentColor` would have resolved to in the surrounding UI.
//
//   node tools/build-powerups.mjs
//
// SVG (not PNG) keeps each power-up a couple of KiB, crisp at any DPR, and
// needs no rasterizer.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

const SOURCES = {
  claude: {
    file: 'assets/powerups/claude.svg',
    w: 24,
    h: 24,
    colors: { light: '#0f1115', dark: '#f9fafb' },
  },
  // Claude Code crab: stompable little enemy. Same viewBox in both themes.
  crab: {
    file: 'assets/items/claudecode.svg',
    w: 24,
    h: 24,
    colors: { light: '#0f1115', dark: '#f9fafb' },
  },
};

function themedSvg(source, color) {
  return source
    .replace(/fill="currentColor"/g, `fill="${color}"`)
    .replace(/\sstyle="[^"]*"/g, '')
    .replace(/\sheight="1em"/, ' height="24"')
    .replace(/\swidth="1em"/, ' width="24"');
}

const assets = {};
for (const [id, def] of Object.entries(SOURCES)) {
  const source = readFileSync(join(ROOT, def.file), 'utf8');
  assets[id] = {};
  for (const [scheme, color] of Object.entries(def.colors)) {
    const svg = themedSvg(source, color);
    assets[id][scheme] = {
      src: `data:image/svg+xml;base64,${Buffer.from(svg, 'utf8').toString('base64')}`,
      w: def.w,
      h: def.h,
    };
  }
}

const target = join(ROOT, 'src/generated/powerups.js');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `// Generated by tools/build-powerups.mjs — do not edit by hand.\nexport const POWERUPS = ${JSON.stringify(assets)};\n`);
console.log(`powerups.js rebuilt (${Object.keys(assets).length} item${Object.keys(assets).length === 1 ? '' : 's'})`);
