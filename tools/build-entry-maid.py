"""Bake 1:1 display-size entry sprite frames for the running-indicator maid.

The entry maid is shown at 30x24 CSS px next to "深度求索中". To keep it crisp
and to avoid any browser-side shrinking/stretching, we pre-render every frame
from the 210x168 run crop down to exactly 30x24 and ship those data URIs.

    python tools/build-entry-maid.py
"""
import base64
import io
import json
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "src", "generated", "assets.js")
OUT = os.path.join(ROOT, "src", "generated", "entry-maid.js")
W, H = 98, 78

source = open(ASSETS, "r", encoding="utf-8").read()
data = json.loads(source[source.index("{"): source.rindex("}") + 1])

result = {}
for scheme in ("light", "dark"):
    frames = []
    for uri in data["maid"][scheme]["frames"]:
        raw = base64.b64decode(uri.split(",", 1)[1])
        frame = Image.open(io.BytesIO(raw)).convert("RGBA")
        frame = frame.resize((W, H), Image.LANCZOS)
        buf = io.BytesIO()
        frame.save(buf, format="PNG", optimize=True)
        frames.append("data:image/png;base64," + base64.b64encode(buf.getvalue()).decode("ascii"))
    result[scheme] = {"w": W, "h": H, "frames": frames}

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build-entry-maid.py — do not edit by hand.\n")
    f.write("export const ENTRY_MAID = ")
    f.write(json.dumps(result, separators=(",", ":")))
    f.write(";\n")

size = os.path.getsize(OUT)
print(f"wrote {OUT} ({size / 1024:.1f} KiB, {W}x{H} per frame, 16 frames x 2 themes)")
