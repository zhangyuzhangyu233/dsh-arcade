// Bake the shooter SVG drop into `src/generated/shooter.js`.
//
// - the player is an SMIL-animated SVG, so it is shipped as inline markup and
//   inserted into the DOM (an <img> would freeze its animation). Only the black
//   version is shipped; the dark theme inverts it with CSS.
// - enemies / elite / boss are static line art, shipped as themed data URIs for
//   canvas drawImage().
//
//   node tools/build-shooter.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SRC = join(ROOT, 'assets', 'shooter');

const dataUri = (name) => 'data:image/svg+xml;base64,' +
  Buffer.from(readFileSync(join(SRC, name), 'utf8'), 'utf8').toString('base64');

const playerSvg = readFileSync(join(SRC, 'player-black.svg'), 'utf8')
  .replace(/^<\?xml[^>]*>\s*/, '')
  .trim();

const REWARD_DIR = join(SRC, 'rewards');
const REWARD_IDS = ['double-shot','triple-shot','screen-clear','damage-up','fire-rate','shield','repair','piercing-laser'];
const rewards = {};
for (const id of REWARD_IDS) {
  rewards[id] = {
    light: dataUri('rewards/black/' + id + '.svg'),
    dark: dataUri('rewards/white/' + id + '.svg'),
  };
}

const images = {
  enemy: { light: dataUri('enemy-black.svg'), dark: dataUri('enemy-white.svg') },
  elite: { light: dataUri('elite-black.svg'), dark: dataUri('elite-white.svg') },
  boss: { light: dataUri('boss-black.svg'), dark: dataUri('boss-white.svg') },
};

const out = `// Generated by tools/build-shooter.mjs — do not edit by hand.
export const SHOOTER = ${JSON.stringify({
  playerSvg,
  playerViewBox: '0 0 1440 624',
  images,
  rewards,
}, null, 0)};
`;

const target = join(ROOT, 'src', 'generated', 'shooter.js');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`shooter.js rebuilt (${(out.length / 1024).toFixed(0)} KiB inline, player ${(playerSvg.length / 1024).toFixed(0)} KiB)`);
